#!/usr/bin/env bash
# Stage the platform's shared code and image recipe into an agent's Docker build context.
# One script for every agent under agents/ (the Methane Hunter's design deferred this to agent three).
#
#   geo_agent/stage_shared.sh <agent_dir> <entry_module>              # code + requirements + Dockerfile
#   geo_agent/stage_shared.sh <agent_dir> <entry_module> dockerfile   # Dockerfile only (after
#                                                                     # `agentcore configure`, which overwrites it)
#
# `agentcore configure/launch` builds from the agent's directory, so the image cannot reach
# geo_agent/. This copies exactly the allowlist below into <agent_dir>/_geo_agent/, appends the
# agent's requirements-agent.txt to the platform's requirements, and generates the Dockerfile from
# the platform's with two changes only: the entrypoint module, and the agent's optional
# Dockerfile.extra lines inserted just before the USER switch (they run as root). So every agent
# runs the same pinned geo stack (Miniforge, GDAL/rasterio pins, the sqlite fix) and cannot drift.
#
# Everything this writes is gitignored. Each agent's tests/test_staging.py parses the two arrays
# below and fails if an agent module imports shared code that is not staged.
#
# Modes: the image COPYs the build context as root and runs as uid 1000 (USER bedrock_agentcore),
# so everything staged must be world-readable whatever the caller's umask. On Oct 22 a deploy run
# under umask 077 staged 600 files and three stable runtimes died at start with
# "PermissionError: ... /app/_geo_agent/config.py". The umask below covers new files; rsync -a
# keeps the source's modes and cp or `>` keep an existing destination's, so the modes are also set
# explicitly after copying (make_readable). geo_agent/tests/test_stage_shared.py runs this under
# umask 077 and checks every staged file.
set -euo pipefail
umask 022

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [ $# -lt 2 ]; then
    echo "usage: $0 <agent_dir> <entry_module> [dockerfile]" >&2
    exit 2
fi
AGENT_DIR="$(cd "$1" && pwd)"
MODULE="$2"
if ! [[ "$MODULE" =~ ^[a-z][a-z0-9_]{0,63}$ ]]; then
    echo "stage_shared.sh: entry module must be a Python module name, got '$MODULE'" >&2
    exit 2
fi
if [ ! -f "$AGENT_DIR/$MODULE.py" ]; then
    echo "stage_shared.sh: $AGENT_DIR/$MODULE.py not found" >&2
    exit 2
fi
DEST="$AGENT_DIR/_geo_agent"

# --- allowlist (keep one item per line; parsed by agents/*/tests/test_staging.py) -----------
SHARED_FILES=(
    config.py
)
SHARED_DIRS=(
    utils
    data
)
# --------------------------------------------------------------------------------------------

generate_dockerfile() {
    local platform="$SRC/Dockerfile_geospatial_agent_on_aws"
    local extra="$AGENT_DIR/Dockerfile.extra"
    # Only these two places differ; fail loudly if the platform Dockerfile ever changes shape.
    grep -q 'python -m geospatial_agent_on_aws' "$platform" || {
        echo "stage_shared.sh: platform Dockerfile CMD changed; update generate_dockerfile()" >&2; exit 1; }
    grep -q '^USER bedrock_agentcore' "$platform" || {
        echo "stage_shared.sh: platform Dockerfile USER line changed; update generate_dockerfile()" >&2; exit 1; }
    {
        echo "# GENERATED by stage_shared.sh from geo_agent/Dockerfile_geospatial_agent_on_aws."
        echo "# Do not edit; change the platform Dockerfile (or this agent's Dockerfile.extra) instead."
        while IFS= read -r line || [ -n "$line" ]; do
            if [[ "$line" == "USER bedrock_agentcore"* ]] && [ -f "$extra" ]; then
                grep -v '^[[:space:]]*#' "$extra" | grep -v '^[[:space:]]*$' || true
            fi
            printf '%s\n' "${line//python -m geospatial_agent_on_aws/python -m $MODULE}"
        done < "$platform"
    } > "$AGENT_DIR/Dockerfile"
    # `>` into an existing file keeps its mode (a 600 Dockerfile from an earlier run stays 600).
    chmod a+r "$AGENT_DIR/Dockerfile"
}

# Everything the image reads from the build context, world-readable (directories traversable).
# The agent's own git-tracked files are included: git writes them under the umask of whatever
# checkout or merge created them, and `COPY . .` puts them in the image with that mode. Gitignored
# files (.env, .env.dev) are never touched: they stay private and .dockerignore keeps them out.
make_readable() {
    chmod -R a+rX "$DEST"
    chmod a+r "$AGENT_DIR/requirements.txt" "$AGENT_DIR/Dockerfile"
    if git -C "$AGENT_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        local f
        while IFS= read -r -d '' f; do
            # A tracked file deleted in the working tree is still listed; skip it.
            if [ -f "$AGENT_DIR/$f" ]; then chmod a+r "$AGENT_DIR/$f"; fi
        done < <(git -C "$AGENT_DIR" ls-files -z -- .)
    fi
}

if [ "${3:-}" = "dockerfile" ]; then
    generate_dockerfile
    echo "Dockerfile regenerated from the platform Dockerfile ($MODULE)."
    exit 0
fi

rm -rf "$DEST"
mkdir -p "$DEST"
for f in "${SHARED_FILES[@]}"; do
    cp "$SRC/$f" "$DEST/$f"
done
for d in "${SHARED_DIRS[@]}"; do
    rsync -a --delete --exclude '__pycache__' --exclude '*.pyc' --exclude '.env*' "$SRC/$d/" "$DEST/$d/"
done
if [ -f "$AGENT_DIR/requirements-agent.txt" ]; then
    { cat "$SRC/requirements.txt"; echo; cat "$AGENT_DIR/requirements-agent.txt"; } > "$AGENT_DIR/requirements.txt"
else
    cp "$SRC/requirements.txt" "$AGENT_DIR/requirements.txt"
fi
generate_dockerfile
make_readable

echo "Staged shared code into $DEST (${SHARED_FILES[*]} ${SHARED_DIRS[*]}), requirements.txt and Dockerfile ($MODULE)."
